    }

    /**
     * v3.0.21: Sanitize a heading-style title string. Always run on H1/H2 writes
     * so REST-driven heading edits never leak trailing nbsp / stray <br> /
     * inside-tag whitespace into the rendered DOM.
     *
     *   - U+00A0 (nbsp) and HTML entities (&nbsp;, &#160;, &#xa0;) → space
     *   - Strip leading/trailing whitespace and stray <br> tags
     *   - Tighten whitespace immediately inside opening/closing tags
     *     so '<span>True Move </span>' becomes '<span>True Move</span>'
     *   - Collapse runs of whitespace to a single space
     */
    public static function sanitize_heading_title($s) {
        if (!is_string($s) || $s === '') return $s;
        $out = str_replace("\xc2\xa0", ' ', $s);
        $out = preg_replace('/&nbsp;|&#160;|&#xa0;/i', ' ', $out);
        $out = preg_replace('/^(?:\s|<br\s*\/?>)+/i', '', $out);
        $out = preg_replace('/(?:\s|<br\s*\/?>)+$/i', '', $out);
        $out = preg_replace('/(<[a-z][^>]*>)\s+/i', '$1', $out);
        $out = preg_replace('/\s+(<\/[a-z][^>]*>)/i', '$1', $out);
        $out = preg_replace('/\s+/', ' ', $out);
        return trim($out);
    }

    public function handle_clear_cache($request) {
        $ip = $this->get_client_ip();
        $body = $request->get_json_params() ?: [];
        $post_id = !empty($body['post_id']) ? absint($body['post_id']) : 0;
        $cleared = [];

        // 1. Per-post Elementor cache: delete _elementor_css postmeta + element cache
        if ($post_id) {
            delete_post_meta($post_id, '_elementor_css');
            delete_post_meta($post_id, '_elementor_inline_svg');
            delete_post_meta($post_id, '_elementor_page_assets');
            $cleared[] = "post_meta cleared for #{$post_id}";

            // Force file regen by deleting the cached CSS file
            $upload_dir = wp_upload_dir();
            $css_file = trailingslashit($upload_dir['basedir']) . 'elementor/css/post-' . $post_id . '.css';
            if (file_exists($css_file)) {
                @unlink($css_file);
                $cleared[] = "css file deleted: {$css_file}";
            }
        }

        // 2. Elementor sitewide cache (clears render fragments, including
        //    Theme Builder theme-post-content cached output)
        if (class_exists('\\Elementor\\Plugin')) {
            try {
                \Elementor\Plugin::$instance->files_manager->clear_cache();
                $cleared[] = 'elementor files_manager->clear_cache()';
            } catch (\Throwable $e) {
                $cleared[] = 'elementor clear_cache failed: ' . $e->getMessage();
            }
        }

        // 3. WP Rocket: post-specific clean if available
        if (function_exists('rocket_clean_post') && $post_id) {
            rocket_clean_post($post_id);
            $cleared[] = "rocket_clean_post({$post_id})";
        } elseif (function_exists('rocket_clean_domain')) {
            rocket_clean_domain();
            $cleared[] = 'rocket_clean_domain()';
        }

        // 4. LiteSpeed Cache (if active)
        if (class_exists('\\LiteSpeed\\Purge') && $post_id) {
            do_action('litespeed_purge_post', $post_id);
            $cleared[] = "litespeed_purge_post({$post_id})";
        }

        // 4b. WP Fastest Cache (v3.1.3). WPFC writes STATIC html to
        //     wp-content/cache/all/ and Apache serves it via mod_rewrite, so a
        //     post_meta-only change (e.g. /seo-meta robots) never invalidates
        //     it: the stale file keeps serving noindex to Googlebot forever.
        //     Only a query-string request falls through to PHP, which is why
        //     this reads as "the write did not land" when it actually did.
        //     Caught on travelbughealth 2026-08-05 (bug-bites noindex fix).
        if (class_exists('WpFastestCache')) {
            if ($post_id && function_exists('wpfc_clear_post_cache_by_id')) {
                wpfc_clear_post_cache_by_id($post_id);
                $cleared[] = "wpfc_clear_post_cache_by_id({$post_id})";
            } elseif (function_exists('wpfc_clear_all_cache')) {
                wpfc_clear_all_cache(true);
                $cleared[] = 'wpfc_clear_all_cache(true)';
            } else {
                do_action('wpfc_clear_all_cache');
                $cleared[] = 'do_action(wpfc_clear_all_cache)';
            }
        }

        // 4c. WP-Optimize (v3.1.5). Its purge is driven by save_post, which a
        //     meta-only REST write never fires. Documented as a known gap since
        //     2026-07-08 (salononyxscottsdale); closing it here.
        if (function_exists('WP_Optimize')) {
            try {
                $wpo = WP_Optimize();
                if (is_object($wpo) && method_exists($wpo, 'get_page_cache')) {
                    $wpo->get_page_cache()->purge();
                    $cleared[] = 'wp_optimize page_cache purge()';
                }
            } catch (\Throwable $e) {
                $cleared[] = 'wp_optimize purge failed: ' . $e->getMessage();
            }
        }

        // 4d. WP Super Cache / W3 Total Cache (same static-file failure mode)
        if (function_exists('wp_cache_clear_cache')) {
            wp_cache_clear_cache();
            $cleared[] = 'wp_cache_clear_cache()';
        }
        if (function_exists('w3tc_flush_all')) {
            w3tc_flush_all();
            $cleared[] = 'w3tc_flush_all()';
        }

        // 5. Generic WP transients tied to Elementor
        global $wpdb;
        $wpdb->query("DELETE FROM {$wpdb->options} WHERE option_name LIKE '_transient_elementor_%' OR option_name LIKE '_transient_timeout_elementor_%'");
        $cleared[] = 'elementor transients deleted';

        $this->audit_log('clear_cache', true, $ip, "post_id=" . ($post_id ?: 'sitewide'));

        return new WP_REST_Response([
            'success' => true,
            'post_id' => $post_id ?: null,
            'actions' => $cleared,
        ], 200);
    }

    // =========================================================================
    // v3.1.7 — SITEMAP DOCTOR
    // =========================================================================
    //
    // Fixes the two failure modes found in the 2026-08-11 fleet audit:
    //
    //  1. A STATIC sitemap.xml / sitemap_index.xml FILE in the web root shadows
    //     the SEO plugin's dynamic sitemap. Apache serves the real file before
    //     WordPress ever handles the request, so Rank Math's sitemap becomes
    //     unreachable at that path and freezes at whatever the file says.
    //     veteranelectrickc + horizonexteriorskc both had this, frozen since
    //     April, and Google had stopped re-reading one of them entirely
    //     (GSC lastDownloaded 2026-03-04).
    //
    //  2. The SEO plugin's own sitemap CACHE goes stale and stops picking up
    //     new posts. Seen fleet-wide with a different cutoff date per site.
    //
    // SAFETY. This route can rename files and write SEO-plugin options, so it
    // is deliberately narrow:
    //   - File ops are RENAME ONLY, never delete, and always reversible via
    //     action=restore.
    //   - Only basenames matching ^sitemap[a-z0-9_-]*\.xml$ , case-insensitive.
    //   - Only in ABSPATH itself. realpath() is re-checked against ABSPATH
    //     after resolution, so symlinks and traversal cannot escape.
    //   - Only if the path is a real file (never a directory or symlink).
    //   - Option writes are restricted to pt_*_robots / pt_*_sitemap style keys
    //     inside the SEO plugin's own option array. The general options
    //     allowlist is NOT widened.
    //   - Every action writes an audit_log entry.
    //   - Default action is the read-only diagnose.

    private function sd_is_safe_sitemap_name($basename) {
        return (bool) preg_match('/^sitemap[a-z0-9_-]*\.xml$/i', $basename);
    }

    /**
     * Resolve a web-root sitemap filename to an absolute path, or false.
     * Rejects anything that is not a plain file sitting directly in ABSPATH.
     */
    private function sd_safe_path($basename, $suffix = '') {
        $basename = wp_basename((string) $basename);
        if (!$this->sd_is_safe_sitemap_name($basename)) return false;
        $root = realpath(ABSPATH);
        if (!$root) return false;
        $full = $root . DIRECTORY_SEPARATOR . $basename . $suffix;
        // Re-resolve the parent to defeat symlink escapes.
        $parent = realpath(dirname($full));
        if ($parent !== $root) return false;
        return $full;
    }

    private function sd_active_seo_plugin() {
        if (defined('RANK_MATH_VERSION') || class_exists('RankMath')) return 'rankmath';
        if (defined('WPSEO_VERSION')) return 'yoast';
        if (defined('AIOSEO_VERSION')) return 'aioseo';
        return 'none';
    }

    /** Invalidate the SEO plugin's cached sitemap XML. */
    private function sd_flush_sitemap_cache() {
        global $wpdb;
        $done = [];
        $seo = $this->sd_active_seo_plugin();

        if ($seo === 'rankmath') {
            // Rank Math caches generated sitemap XML. Preferred path is its own
            // invalidator; fall back to clearing the cache table + transients.
            if (class_exists('\\RankMath\\Sitemap\\Cache')) {
                if (method_exists('\\RankMath\\Sitemap\\Cache', 'invalidate_storage')) {
                    \RankMath\Sitemap\Cache::invalidate_storage();
                    $done[] = 'rankmath_cache_invalidate_storage';
                }
            }
            if (function_exists('rank_math')) {
                do_action('rank_math/sitemap/invalidate_object_type', 'post');
                $done[] = 'rankmath_invalidate_object_type';
            }
            $table = $wpdb->prefix . 'rank_math_sitemap_cache';
            if ($wpdb->get_var($wpdb->prepare("SHOW TABLES LIKE %s", $table)) === $table) {
                $n = $wpdb->query("DELETE FROM {$table}");
                $done[] = 'rankmath_cache_table_rows_deleted=' . intval($n);
            }
            $n2 = $wpdb->query(
                "DELETE FROM {$wpdb->options} WHERE option_name LIKE '_transient_rank_math_sitemap%'
                 OR option_name LIKE '_transient_timeout_rank_math_sitemap%'"
            );
            $done[] = 'rankmath_transients_deleted=' . intval($n2);
        } elseif ($seo === 'yoast') {
            if (function_exists('wpseo_invalidate_sitemap_cache')) {
                wpseo_invalidate_sitemap_cache('post');
                $done[] = 'yoast_invalidate';
            }
            $n = $wpdb->query(
                "DELETE FROM {$wpdb->options} WHERE option_name LIKE '_transient_wpseo_sitemap%'
                 OR option_name LIKE '_transient_timeout_wpseo_sitemap%'"
            );
            $done[] = 'yoast_transients_deleted=' . intval($n);
        }

        wp_cache_flush();
        $done[] = 'object_cache_flushed';
        return $done;
    }

    /**
     * Set Rank Math per-post-type robots / sitemap flags without opening the
     * general options allowlist. Only pt_{type}_* keys inside Rank Math's own
     * titles + sitemap option arrays are touched.
     */
    private function sd_set_post_type_flags($post_type, $index, $in_sitemap, $archive_index) {
        $post_type = sanitize_key($post_type);
        if (!$post_type) return ['error' => 'post_type required'];
        if ($this->sd_active_seo_plugin() !== 'rankmath') {
            return ['error' => 'post-type flags currently implemented for Rank Math only'];
        }
        $changed = [];

        if ($index !== null || $archive_index !== null) {
            $titles = get_option('rank-math-options-titles', []);
            if (!is_array($titles)) $titles = [];
            if ($index !== null) {
                $titles['pt_' . $post_type . '_custom_robots'] = 'on';
                $titles['pt_' . $post_type . '_robots'] = $index
                    ? ['index'] : ['noindex'];
                $changed[] = 'pt_' . $post_type . '_robots=' . ($index ? 'index' : 'noindex');
            }
            if ($archive_index !== null) {
                $titles['pt_' . $post_type . '_archive_custom_robots'] = 'on';
                $titles['pt_' . $post_type . '_archive_robots'] = $archive_index
                    ? ['index'] : ['noindex'];
                $changed[] = 'pt_' . $post_type . '_archive_robots='
                    . ($archive_index ? 'index' : 'noindex');
            }
            update_option('rank-math-options-titles', $titles);
        }

        if ($in_sitemap !== null) {
            $sm = get_option('rank-math-options-sitemap', []);
            if (!is_array($sm)) $sm = [];
            $sm['pt_' . $post_type . '_sitemap'] = $in_sitemap ? 'on' : 'off';
            update_option('rank-math-options-sitemap', $sm);
            $changed[] = 'pt_' . $post_type . '_sitemap=' . ($in_sitemap ? 'on' : 'off');
        }

        return ['changed' => $changed];
    }

    /**
     * v3.2.4: Active-theme file read/write.
     *
     * Confined to get_stylesheet_directory(). Every write requires the sha256
     * of the current content (no blind overwrites), PHP is parse-checked
     * before it touches disk, the previous content is kept in a non-autoload
     * option (last 10 per file, never web-reachable), and the swap is a
     * same-directory rename. functions.php is refused unless allow_bootstrap
     * is set: it loads on REST requests too, so a runtime fatal there would
     * take down this endpoint and with it the restore path. Template files
     * (header.php, archive-*.php) only load on front-end requests, so REST,
     * and restore, survive a bad template.
     */
    public function handle_theme_file($request) {
        $ip = $this->get_client_ip();
        $dir = realpath(get_stylesheet_directory());
        if (!$dir || !is_dir($dir)) {
            return new WP_Error('theme_file', 'Active theme directory not found.', ['status' => 500]);
        }
        $theme = get_stylesheet();
        $is_get = $request->get_method() === 'GET';
        $body = $is_get ? [] : ($request->get_json_params() ?: []);
        $path = $is_get ? (string) $request->get_param('path') : (string) ($body['path'] ?? '');
        $action = $is_get ? 'read' : sanitize_key($body['action'] ?? 'write');

        if ($is_get && $path === '') {
            $files = [];
            $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS));
            foreach ($it as $f) {
                if (!$f->isFile()) continue;
                $rel = ltrim(str_replace('\\', '/', substr($f->getPathname(), strlen($dir))), '/');
                if (strpos($rel, 'node_modules/') === 0 || strpos($rel, '.git/') === 0) continue;
                $files[] = ['path' => $rel, 'bytes' => $f->getSize(), 'modified' => gmdate('c', $f->getMTime())];
                if (count($files) >= 2000) break;
            }
            usort($files, function ($a, $b) { return strcmp($a['path'], $b['path']); });
            $this->audit_log('theme_file', true, $ip, 'list ' . count($files));
            return new WP_REST_Response(['success' => true, 'theme' => $theme, 'files' => $files], 200);
        }

        $abs = $this->tf_safe_path($dir, $path);
        if (is_wp_error($abs)) {
            $this->audit_log('theme_file', false, $ip, $action . ' ' . $path . ' ' . $abs->get_error_message());
            return $abs;
        }
        $rel = ltrim(substr($abs, strlen($dir)), '/');
        $backups = get_option('sadie_theme_file_backups', []);
        if (!is_array($backups)) $backups = [];
        $key = $theme . '/' . $rel;

        if ($action === 'read') {
            if (!is_file($abs)) return new WP_Error('not_found', 'File not found: ' . $rel, ['status' => 404]);
            $c = file_get_contents($abs);
            $this->audit_log('theme_file', true, $ip, 'read ' . $rel);
            return new WP_REST_Response([
                'success' => true, 'theme' => $theme, 'path' => $rel,
                'sha256' => hash('sha256', $c), 'bytes' => strlen($c),
                'modified' => gmdate('c', filemtime($abs)), 'content' => $c,
                'backups' => array_map(function ($b) { return ['id' => $b['id'], 'saved' => $b['saved'], 'sha256' => $b['sha256']]; }, $backups[$key] ?? []),
            ], 200);
        }

        if ($action === 'backups') {
            return new WP_REST_Response(['success' => true, 'path' => $rel,
                'backups' => array_map(function ($b) { return ['id' => $b['id'], 'saved' => $b['saved'], 'sha256' => $b['sha256'], 'bytes' => strlen($b['content'])]; }, $backups[$key] ?? [])], 200);
        }

        if ($action === 'restore') {
            $id = (string) ($body['backup_id'] ?? '');
            $found = null;
            foreach ($backups[$key] ?? [] as $b) { if ($b['id'] === $id) $found = $b; }
            if (!$found) return new WP_Error('not_found', 'No backup ' . $id . ' for ' . $rel, ['status' => 404]);
            $content = $found['content'];
        } elseif ($action === 'write') {
            if (!array_key_exists('content', $body) || !is_string($body['content'])) {
                return new WP_Error('bad_request', 'content (string) is required.', ['status' => 400]);
            }
            $content = $body['content'];
            if (basename($rel) === 'functions.php' && $rel === 'functions.php' && empty($body['allow_bootstrap'])) {
                return new WP_Error('forbidden', 'functions.php loads on REST requests; a fatal there removes the restore path. Pass allow_bootstrap=true to accept that.', ['status' => 403]);
            }
        } else {
            return new WP_Error('bad_request', 'action must be write, restore or backups.', ['status' => 400]);
        }

        if (strpos($content, "\0") !== false) {
            return new WP_Error('bad_request', 'content contains a NUL byte.', ['status' => 400]);
        }
        $exists = is_file($abs);
        $current = $exists ? file_get_contents($abs) : '';
        $current_sha = $exists ? hash('sha256', $current) : '';
        $expected = (string) ($body['expected_sha256'] ?? '');
        if ($expected !== $current_sha) {
            $this->audit_log('theme_file', false, $ip, $action . ' ' . $rel . ' sha mismatch');
            return new WP_Error('conflict', 'expected_sha256 does not match the file on disk (use "" for a new file).',
                ['status' => 409, 'current_sha256' => $current_sha]);
        }
        if (substr($rel, -4) === '.php') {
            try {
                token_get_all($content, TOKEN_PARSE);
            } catch (\ParseError $e) {
                $this->audit_log('theme_file', false, $ip, $action . ' ' . $rel . ' parse error');
                return new WP_Error('parse_error', 'PHP parse error line ' . $e->getLine() . ': ' . $e->getMessage(), ['status' => 422]);
            }
        }

        $backup_id = null;
        if ($exists) {
            $backup_id = gmdate('Ymd\THis\Z') . '-' . substr($current_sha, 0, 8);
            $list = $backups[$key] ?? [];
            $list[] = ['id' => $backup_id, 'saved' => gmdate('c'), 'sha256' => $current_sha, 'content' => $current];
            $backups[$key] = array_slice($list, -10);
            if (!update_option('sadie_theme_file_backups', $backups, false) && get_option('sadie_theme_file_backups') != $backups) {
                return new WP_Error('theme_file', 'Could not store the backup; nothing was written.', ['status' => 500]);
            }
        }
        $tmp = dirname($abs) . '/.sadie-tmp-' . wp_generate_password(8, false) . '-' . basename($abs);
        if (file_put_contents($tmp, $content, LOCK_EX) !== strlen($content)) {
            @unlink($tmp);
            return new WP_Error('theme_file', 'Write failed (check file permissions).', ['status' => 500]);
        }
        if ($exists) @chmod($tmp, fileperms($abs) & 0777);
        if (!@rename($tmp, $abs)) {
            @unlink($tmp);
            return new WP_Error('theme_file', 'Rename into place failed.', ['status' => 500]);
        }
        if (function_exists('opcache_invalidate')) @opcache_invalidate($abs, true);
        clearstatcache(true, $abs);
        $new_sha = hash('sha256', file_get_contents($abs));
        $this->audit_log('theme_file', true, $ip, $action . ' ' . $rel . ' ' . substr($new_sha, 0, 12));
        return new WP_REST_Response([
            'success' => $new_sha === hash('sha256', $content),
            'action' => $action, 'theme' => $theme, 'path' => $rel,
            'sha256' => $new_sha, 'previous_sha256' => $current_sha, 'backup_id' => $backup_id,
            'reversible' => $backup_id ? 'POST {"action":"restore","path":"' . $rel . '","backup_id":"' . $backup_id . '","expected_sha256":"' . $new_sha . '"}' : null,
        ], 200);
    }

    private function tf_safe_path($dir, $path) {
        $path = str_replace('\\', '/', trim($path));
        if ($path === '' || strpos($path, "\0") !== false || $path[0] === '/' || preg_match('#(^|/)\.\.?(/|$)#', $path)) {
            return new WP_Error('bad_request', 'Invalid path.', ['status' => 400]);
        }
        $ext = strtolower(pathinfo($path, PATHINFO_EXTENSION));
        if (!in_array($ext, ['php', 'css', 'js', 'json', 'html', 'txt', 'svg'], true)) {
            return new WP_Error('bad_request', 'Extension not allowed: ' . $ext, ['status' => 400]);
        }
        $parent = realpath($dir . '/' . dirname($path));
        if (!$parent || ($parent !== $dir && strpos($parent, $dir . '/') !== 0)) {
            return new WP_Error('bad_request', 'Path is outside the active theme.', ['status' => 400]);
        }
        $abs = $parent . '/' . basename($path);
        if (is_link($abs)) return new WP_Error('bad_request', 'Symlinks are not editable.', ['status' => 400]);
        return $abs;
    }

    public function handle_sitemap_doctor($request) {
        $ip = $this->get_client_ip();
        $body = $request->get_json_params() ?: [];
        $action = isset($body['action']) ? sanitize_key($body['action']) : 'diagnose';

        $seo = $this->sd_active_seo_plugin();
        $root = realpath(ABSPATH);

        // Which shadowing files actually exist right now.
        $candidates = ['sitemap.xml', 'sitemap_index.xml', 'sitemap-index.xml'];
        $shadowing = [];
        $backups = [];
        foreach ($candidates as $name) {
            $p = $this->sd_safe_path($name);
            if ($p && is_file($p) && !is_link($p)) {
                $shadowing[] = [
                    'file' => $name,
                    'bytes' => filesize($p),
                    'modified' => gmdate('c', filemtime($p)),
                ];
            }
            $b = $this->sd_safe_path($name, '.sadie-bak');
            if ($b && is_file($b)) $backups[] = $name . '.sadie-bak';
        }

        if ($action === 'diagnose') {
            $this->audit_log('sitemap_doctor', true, $ip, 'diagnose');
            return new WP_REST_Response([
                'success' => true,
                'action' => 'diagnose',
                'seo_plugin' => $seo,
                'abspath' => $root,
                'shadowing_files' => $shadowing,
                'existing_backups' => $backups,
                'note' => $shadowing
                    ? 'Static sitemap file(s) present in web root. Apache serves these before WordPress, so the SEO plugin sitemap at these paths is unreachable.'
                    : 'No static sitemap files shadowing the web root.',
            ], 200);
        }

        if ($action === 'unshadow') {
            if (!$shadowing) {
                return new WP_REST_Response([
                    'success' => true, 'action' => 'unshadow',
                    'renamed' => [], 'note' => 'Nothing to unshadow.',
                ], 200);
            }
            $renamed = []; $failed = [];
            foreach ($shadowing as $s) {
                $src = $this->sd_safe_path($s['file']);
                $dst = $this->sd_safe_path($s['file'], '.sadie-bak');
                if (!$src || !$dst) { $failed[] = $s['file'] . ' (path rejected)'; continue; }
                if (@rename($src, $dst)) $renamed[] = $s['file'] . ' -> ' . basename($dst);
                else $failed[] = $s['file'] . ' (rename failed, check file permissions)';
            }
            $flushed = $renamed ? $this->sd_flush_sitemap_cache() : [];
            $this->audit_log('sitemap_doctor', empty($failed), $ip,
                'unshadow renamed=' . count($renamed) . ' failed=' . count($failed));
            return new WP_REST_Response([
                'success' => empty($failed),
                'action' => 'unshadow',
                'renamed' => $renamed,
                'failed' => $failed,
                'cache' => $flushed,
                'reversible' => 'POST {"action":"restore"} puts the files back.',
            ], empty($failed) ? 200 : 500);
        }

        if ($action === 'restore') {
            $restored = []; $failed = [];
            foreach ($candidates as $name) {
                $bak = $this->sd_safe_path($name, '.sadie-bak');
                $dst = $this->sd_safe_path($name);
                if (!$bak || !$dst || !is_file($bak)) continue;
                if (@rename($bak, $dst)) $restored[] = $name;
                else $failed[] = $name;
            }
            $this->audit_log('sitemap_doctor', empty($failed), $ip,
                'restore restored=' . count($restored));
            return new WP_REST_Response([
                'success' => empty($failed), 'action' => 'restore',
                'restored' => $restored, 'failed' => $failed,
            ], empty($failed) ? 200 : 500);
        }

        if ($action === 'flush') {
            $flushed = $this->sd_flush_sitemap_cache();
            $this->audit_log('sitemap_doctor', true, $ip, 'flush');
            return new WP_REST_Response([
                'success' => true, 'action' => 'flush',
                'seo_plugin' => $seo, 'cache' => $flushed,
            ], 200);
        }

        if ($action === 'set_post_type_sitemap') {
            $pt = isset($body['post_type']) ? $body['post_type'] : '';
            $index = array_key_exists('index', $body) ? (bool) $body['index'] : null;
            $in_sm = array_key_exists('in_sitemap', $body) ? (bool) $body['in_sitemap'] : null;
            $arch  = array_key_exists('archive_index', $body) ? (bool) $body['archive_index'] : null;
            if ($index === null && $in_sm === null && $arch === null) {
                return new WP_Error('bad_request',
                    'Provide at least one of: index, in_sitemap, archive_index.', ['status' => 400]);
            }
            $res = $this->sd_set_post_type_flags($pt, $index, $in_sm, $arch);
            if (!empty($res['error'])) {
                $this->audit_log('sitemap_doctor', false, $ip, 'set_post_type_sitemap ' . $res['error']);
                return new WP_Error('sitemap_doctor', $res['error'], ['status' => 400]);
            }
            $flushed = $this->sd_flush_sitemap_cache();
            $this->audit_log('sitemap_doctor', true, $ip,
                'set_post_type_sitemap ' . $pt . ' ' . implode(',', $res['changed']));
            return new WP_REST_Response([
                'success' => true, 'action' => 'set_post_type_sitemap',
                'post_type' => sanitize_key($pt), 'changed' => $res['changed'],
                'cache' => $flushed,
            ], 200);
        }

        return new WP_Error('bad_request',
            'Unknown action. Use diagnose | unshadow | restore | flush | set_post_type_sitemap.',
            ['status' => 400]);
    }

