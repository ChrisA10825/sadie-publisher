    /**
     * POST /sadie-publisher/v1/redirections
     * Body: { source, target, header_code (default 301), comparison (default 'exact'), category }
     * Inserts (or updates if matching source already exists) into RankMath's
     * wp_rank_math_redirections table. Auth: HMAC.
     */
    public function handle_redirection_add($request) {
        $ip = $this->get_client_ip();
        $params = $request->get_json_params() ?: [];

        $source     = isset($params['source']) ? trim((string) $params['source']) : '';
        $target     = isset($params['target']) ? trim((string) $params['target']) : '';
        $code       = isset($params['header_code']) ? absint($params['header_code']) : 301;
        $comparison = isset($params['comparison']) ? sanitize_key($params['comparison']) : 'exact';
        $status     = isset($params['status']) ? sanitize_key($params['status']) : 'active';

        if ($source === '' || $target === '') {
            return new WP_Error('bad_request', 'source and target are required.', ['status' => 400]);
        }
        if (!in_array($code, [301, 302, 307, 410, 451], true)) {
            $code = 301;
        }
        if (!in_array($comparison, ['exact', 'contains', 'start', 'end', 'regex'], true)) {
            $comparison = 'exact';
        }
        if (!in_array($status, ['active', 'inactive', 'trashed'], true)) {
            $status = 'active';
        }

        // Strip leading slash on source pattern (RankMath stores without leading /)
        $source_pattern = ltrim($source, '/');

        global $wpdb;
        $table = $wpdb->prefix . 'rank_math_redirections';

        // Verify table exists
        $exists = $wpdb->get_var($wpdb->prepare("SHOW TABLES LIKE %s", $table));
        if ($exists !== $table) {
            return new WP_Error('rankmath_missing', 'wp_rank_math_redirections table not found. Is RankMath active and Redirections module enabled?', ['status' => 412]);
        }

        // RankMath stores sources as serialized array of {pattern, comparison}
        $sources_serialized = maybe_serialize([[
            'pattern'    => $source_pattern,
            'comparison' => $comparison,
            'ignore'     => '',
        ]]);

        // Check for existing redirection with this source (by serialized blob match)
        $existing_id = $wpdb->get_var($wpdb->prepare(
            "SELECT id FROM {$table} WHERE sources = %s LIMIT 1",
            $sources_serialized
        ));

        $row = [
            'sources'      => $sources_serialized,
            'url_to'       => esc_url_raw($target),
            'header_code'  => $code,
            'hits'         => 0,
            'status'       => $status,
            'updated'      => current_time('mysql'),
        ];

        if ($existing_id) {
            $wpdb->update($table, $row, ['id' => $existing_id]);
            $action = 'updated';
            $rid = (int) $existing_id;
        } else {
            $row['created'] = current_time('mysql');
            $wpdb->insert($table, $row);
            $action = 'created';
            $rid = (int) $wpdb->insert_id;
        }

        // Bust RankMath's redirection cache so the new rule fires immediately
        if (class_exists('\\RankMath\\Redirections\\Cache')) {
            try {
                \RankMath\Redirections\Cache::purge();
            } catch (\Throwable $e) { /* non-fatal */ }
        }
        // Also clear object cache for the redirections option
        wp_cache_delete('rank_math_redirections', 'options');

        $this->audit_log('redirection_add', true, $ip, "id={$rid} {$action} {$source} -> {$target} ({$code})");

        return new WP_REST_Response([
            'success'    => true,
            'action'     => $action,
            'id'         => $rid,
            'source'     => $source_pattern,
            'target'     => $target,
            'header_code'=> $code,
            'comparison' => $comparison,
            'status'     => $status,
        ], 200);
    }

