        // v3.0.23: Internal-link graph readouts from RankMath's two link tables.
        // Lets Sadie identify orphan / low-authority posts and propose internal
        // link inserts from high-authority pages.
        // - /internal-link-graph/summary  → per-post counts (incoming/outgoing/external)
        // - /internal-link-graph/edges    → source→target edge list
        register_rest_route($ns, '/internal-link-graph/summary', [
            'methods' => 'GET',
            'callback' => [$this, 'handle_link_graph_summary'],
            'permission_callback' => [$this, 'verify_request'],
