    private function prepare_content_for_builder($content, $builder, $trusted = false) {
        // wp_kses_post strips style= attributes from <div> elements, which breaks
        // Sadie's brand-color callout components (blog-callout, blog-cards, etc.).
        // All content arriving via the Sadie Publisher REST API is already authenticated
        // via HMAC-SHA256, so kses sanitization is redundant and destructive here.
        // We skip it for trusted API calls; still run it for any future untrusted paths.
        if (!$trusted) {
            $content = wp_kses_post($content);
        }

        switch ($builder['name']) {
            case 'gutenberg':
                return $this->convert_to_gutenberg_blocks($content);

            case 'elementor':
                // Elementor reads from post_content for blog posts
                // The Elementor template is applied by the theme, not stored per-post for standard posts
                // We just need clean HTML
                return $content;

            case 'flatsome':
                // Flatsome uses standard post_content for blog posts
                // UX Builder is primarily for pages, not posts
                return $content;

            case 'divi':
                // Divi Builder: standard HTML works for posts
                // Divi applies its blog template around the content
                return $content;

            default:
                // Classic editor / other builders: standard HTML
                return $content;
        }
    }

    private function convert_to_gutenberg_blocks($html) {
        // If content already has block markers, return as-is
        if (strpos($html, '<!-- wp:') !== false) {
            return $html;
        }

        // Split HTML into logical sections and wrap in appropriate blocks
        // For blog posts, wrapping in a single html block is the most reliable approach
        // This ensures the content renders correctly regardless of theme
        $blocks = [];

        // Use DOMDocument for reliable parsing
        if (class_exists('DOMDocument') && !empty(trim($html))) {
            $doc = new \DOMDocument();
            // Suppress warnings from malformed HTML
            @$doc->loadHTML(
                '<!DOCTYPE html><html><head><meta charset="UTF-8"></head><body>' . $html . '</body></html>',
                LIBXML_HTML_NOIMPLIED | LIBXML_HTML_NODEFDTD
            );

            $body = $doc->getElementsByTagName('body')->item(0);
            if ($body) {
                foreach ($body->childNodes as $node) {
                    if ($node->nodeType !== XML_ELEMENT_NODE) {
                        continue;
                    }

                    $tag = strtolower($node->nodeName);
                    $inner = $doc->saveHTML($node);

                    switch ($tag) {
                        case 'h1':
                        case 'h2':
                        case 'h3':
                        case 'h4':
                        case 'h5':
                        case 'h6':
                            $level = (int) substr($tag, 1);
                            $text = $node->textContent;
                            $blocks[] = "<!-- wp:heading {\"level\":{$level}} -->\n<{$tag} class=\"wp-block-heading\">{$text}</{$tag}>\n<!-- /wp:heading -->";
                            break;

                        case 'p':
                            $blocks[] = "<!-- wp:paragraph -->\n{$inner}\n<!-- /wp:paragraph -->";
                            break;

                        case 'ul':
                            $blocks[] = "<!-- wp:list -->\n{$inner}\n<!-- /wp:list -->";
                            break;

                        case 'ol':
                            $blocks[] = "<!-- wp:list {\"ordered\":true} -->\n{$inner}\n<!-- /wp:list -->";
                            break;

                        case 'blockquote':
                            $blocks[] = "<!-- wp:quote -->\n{$inner}\n<!-- /wp:quote -->";
                            break;

                        case 'img':
                            $src = $node->getAttribute('src');
                            $alt = $node->getAttribute('alt');
                            $blocks[] = "<!-- wp:image -->\n<figure class=\"wp-block-image\"><img src=\"{$src}\" alt=\"{$alt}\"/></figure>\n<!-- /wp:image -->";
                            break;

                        case 'figure':
                            $blocks[] = "<!-- wp:image -->\n{$inner}\n<!-- /wp:image -->";
                            break;

                        case 'table':
                            $blocks[] = "<!-- wp:table -->\n<figure class=\"wp-block-table\">{$inner}</figure>\n<!-- /wp:table -->";
                            break;

                        default:
                            // Wrap unknown elements in an html block
                            $blocks[] = "<!-- wp:html -->\n{$inner}\n<!-- /wp:html -->";
                            break;
                    }
                }
            }
        }

        if (empty($blocks)) {
            // Fallback: wrap entire content in a single HTML block
            return "<!-- wp:html -->\n{$html}\n<!-- /wp:html -->";
        }

        return implode("\n\n", $blocks);
    }

    /**
     * v3.2.6: validate optional `parent` and `template` for pages.
     * Returns [] when neither was sent, ['post_parent' => int, 'template' => string]
     * for what was sent and valid, or WP_Error (400) when a value is invalid.
     * Never silently ignores a bad value: a wrong parent changes the live URL.
     */
    private function page_hierarchy_args($params, $post_type, $self_id) {
        $out = [];
        $has_parent = is_array($params) && array_key_exists('parent', $params);
        $has_template = is_array($params) && array_key_exists('template', $params);
        if (!$has_parent && !$has_template) {
            return $out;
        }
        if ($post_type !== 'page') {
            return new WP_Error('bad_request', 'parent and template apply to pages only.', ['status' => 400]);
        }
        if ($has_parent) {
            $parent = absint($params['parent']);
            if ($parent > 0) {
                $p = get_post($parent);
                if (!$p || $p->post_type !== 'page') {
                    return new WP_Error('bad_request', "parent {$parent} is not an existing page.", ['status' => 400]);
                }
                if ($self_id && $parent === (int) $self_id) {
                    return new WP_Error('bad_request', 'A page cannot be its own parent.', ['status' => 400]);
                }
                if ($self_id && in_array((int) $self_id, array_map('intval', get_post_ancestors($parent)), true)) {
                    return new WP_Error('bad_request', 'parent would create a loop.', ['status' => 400]);
                }
            }
            $out['post_parent'] = $parent;
        }
        if ($has_template) {
            $tpl = sanitize_text_field((string) $params['template']);
            if ($tpl !== '' && $tpl !== 'default') {
                $templates = wp_get_theme()->get_page_templates(null, 'page');
                if (!isset($templates[$tpl])) {
                    return new WP_Error('bad_request', "template '{$tpl}' does not exist in the active theme.", ['status' => 400]);
                }
            } else {
                $tpl = 'default';
            }
            $out['template'] = $tpl;
        }
        return $out;
    }

