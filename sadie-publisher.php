    public function handle_update($request) {
        $ip = $this->get_client_ip();
        $post_id = absint($request->get_param('id'));
        $params = $request->get_json_params();

        $post = get_post($post_id);
        if (!$post) {
            $this->audit_log('update', false, $ip, "Post #{$post_id} not found");
            return new WP_Error('not_found', 'Post not found.', ['status' => 404]);
        }

        $post_data = ['ID' => $post_id];

        if (!empty($params['title'])) {
            $post_data['post_title'] = sanitize_text_field($params['title']);
        }
        if (!empty($params['content'])) {
            $builder = $this->detect_builder();
            // trusted=true: content arrived via HMAC-verified REST API; skip wp_kses_post
            $post_data['post_content'] = $this->prepare_content_for_builder($params['content'], $builder, true);
        }
        if (!empty($params['status'])) {
            $allowed = ['draft', 'publish', 'pending', 'future', 'private'];
            if (in_array($params['status'], $allowed, true)) {
                $post_data['post_status'] = $params['status'];
            }
        }
        if (!empty($params['slug'])) {
            $post_data['post_name'] = sanitize_title($params['slug']);
        }
        if (!empty($params['excerpt'])) {
            $post_data['post_excerpt'] = sanitize_textarea_field($params['excerpt']);
        }
        if (!empty($params['date'])) {
            $post_data['post_date'] = sanitize_text_field($params['date']);
            if (($post_data['post_status'] ?? '') === 'future') {
                $post_data['post_date_gmt'] = get_gmt_from_date($params['date']);
            }
        }

        $hier = $this->page_hierarchy_args($params, $post->post_type, $post_id);
        if (is_wp_error($hier)) {
            $this->audit_log('update', false, $ip, $hier->get_error_message());
            return $hier;
        }
        if (array_key_exists('post_parent', $hier)) {
            $post_data['post_parent'] = $hier['post_parent'];
        }

        // WordPress requires edit_date=true to actually change post_date on updates
        if (!empty($params['date'])) {
            $post_data['edit_date'] = true;
        }

        $result = wp_update_post($post_data, true);
        if (is_wp_error($result)) {
            $this->audit_log('update', false, $ip, $result->get_error_message());
            return $result;
        }

        if (isset($hier['template'])) {
            update_post_meta($post_id, '_wp_page_template', $hier['template']);
        }

        // Update SEO if provided
        if (!empty($params['seo'])) {
            $this->set_seo_meta($post_id, $params['seo']);
        }

        // Update categories if provided
        if (!empty($params['categories'])) {
            $this->assign_categories($post_id, $params['categories']);
        }

        // Update Elementor data if provided (allows direct editing of Elementor JSON)
        if (!empty($params['elementor_data'])) {
            $elementor_data = $params['elementor_data'];
            if (is_string($elementor_data)) {
                $decoded = json_decode($elementor_data, true);
                if (json_last_error() === JSON_ERROR_NONE) {
                    $elementor_data = $decoded;
                }
            }
            if (is_array($elementor_data)) {
                // v3.0.21: walk the tree and sanitize every heading widget's title
                // so REST-driven Elementor edits never leak nbsp/stray <br>/inside-tag
                // whitespace into the rendered DOM.
                $self = $this;
                $sanitize_walk = function (&$node) use (&$sanitize_walk, $self) {
                    if (!is_array($node)) return;
                    if (isset($node['widgetType']) && $node['widgetType'] === 'heading'
                        && isset($node['settings']['title']) && is_string($node['settings']['title'])) {
                        $node['settings']['title'] = self::sanitize_heading_title($node['settings']['title']);
                    }
                    if (isset($node['elements']) && is_array($node['elements'])) {
                        foreach ($node['elements'] as &$child) {
                            $sanitize_walk($child);
                        }
                        unset($child);
                    }
                    // Top-level may itself be an array of sections
                    foreach ($node as $k => &$v) {
                        if (is_array($v) && !in_array($k, ['settings','elements','editSettings','defaultEditSettings'], true)) {
                            $sanitize_walk($v);
                        }
                    }
                    unset($v);
                };
                $is_list = (function_exists('array_is_list')
                    ? array_is_list($elementor_data)
                    : (array_keys($elementor_data) === range(0, count($elementor_data) - 1)));
                if ($is_list) {
                    foreach ($elementor_data as &$section) { $sanitize_walk($section); }
                    unset($section);
                } else {
                    $sanitize_walk($elementor_data);
                }
                update_post_meta($post_id, '_elementor_data', wp_slash(wp_json_encode($elementor_data)));
                update_post_meta($post_id, '_elementor_edit_mode', 'builder');
            }
        }

        // Update featured image if provided
        $settings = get_option($this->settings_option, []);
        if (!empty($params['featured_image']) && ($settings['allow_images'] ?? true)) {
            $img_data = is_array($params['featured_image']) ? $params['featured_image'] : ['url' => $params['featured_image']];
            $image_id = $this->upload_image_from_url(
                $img_data['url'],
                $img_data['alt'] ?? ($params['title'] ?? $post->post_title),
                $post_id
            );
            if ($image_id && !is_wp_error($image_id)) {
                set_post_thumbnail($post_id, $image_id);
            }
        }

        // Sideload external images in content to local media library
        $settings = get_option($this->settings_option, []);
        if ($settings['allow_images'] ?? true) {
            $this->sideload_content_images($post_id);
        }

        update_post_meta($post_id, '_sadie_updated_at', current_time('mysql'));

        $this->audit_log('update', true, $ip, "Post #{$post_id}");

        if (get_post_status($post_id) === 'publish') {
            $this->ping_indexnow(get_permalink($post_id));
        }

        return new WP_REST_Response([
            'success' => true,
            'post_id' => $post_id,
            'post_url' => get_permalink($post_id),
            'status' => get_post_status($post_id),
        ], 200);
    }

