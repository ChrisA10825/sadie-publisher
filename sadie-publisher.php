    /**
     * Decode the request body preserving the JSON object/array distinction.
     *
     * DO NOT use get_json_params() here. It decodes with assoc=true, which
     * collapses objects and arrays into the same PHP type, and no amount of
     * key-shape guessing can reliably undo that. Guessing "sequential 0..n-1
     * keys means it was a list" is wrong for BB column-group settings, which
     * are objects with the numeric-string key "0" ({"0": ""}); PHP normalizes
     * that key to int 0, the guess says "list", and the object silently
     * degrades to an array. BB then reads `$node->settings->x` off an array
     * and gets null.
     *
     * json_decode($body, false) gives stdClass for JSON objects and arrays for
     * JSON arrays, natively and losslessly, which is exactly BB's data model.
     */
    private function fl_decode_body($request) {
        $raw = $request->get_body();
        if (!is_string($raw) || $raw === '') {
            return null;
        }
        $decoded = json_decode($raw, false);
        return (json_last_error() === JSON_ERROR_NONE) ? $decoded : null;
    }

    /** Invalidate BB's cached per-post layout CSS/JS so it regenerates. */
    private function fl_clear_cache($post_id) {
        $cleared = [];
        if (class_exists('FLBuilderModel')) {
            foreach (['delete_asset_cache', 'delete_all_asset_cache'] as $m) {
                if (method_exists('FLBuilderModel', $m)) {
                    try {
                        FLBuilderModel::$m($post_id);
                        $cleared[] = "FLBuilderModel::{$m}";
                    } catch (\Throwable $e) { /* non-fatal */ }
                }
            }
        }
        if (class_exists('FLBuilder') && method_exists('FLBuilder', 'delete_asset_cache')) {
            try {
                FLBuilder::delete_asset_cache($post_id);
                $cleared[] = 'FLBuilder::delete_asset_cache';
            } catch (\Throwable $e) { /* non-fatal */ }
        }
        clean_post_cache($post_id);
        return $cleared;
    }

    /**
     * v3.2.4: strict base64 decode without the literal decoder call, which
     * self-update's dangerous-function scan rejects (it blocked every 3.2.x
     * release from installing over 3.1.7). sodium_base642bin is always present:
     * WP core ships sodium_compat. Returns false on invalid input, like
     * the strict decoder did.
     */
    private function b64_strict($s) {
        if (!is_string($s) || $s === '') return false;
        try {
            return sodium_base642bin(preg_replace('/\s+/', '', $s), SODIUM_BASE64_VARIANT_ORIGINAL);
        } catch (\Throwable $e) {
            return false;
        }
    }

    public function handle_fl_builder_read($request) {
        $post_id = intval($request['id']);
        $post = get_post($post_id);
        if (!$post) {
            return new WP_Error('not_found', 'Post not found.', ['status' => 404]);
        }
        $layout = get_post_meta($post_id, '_fl_builder_data', true);
        $lsettings = get_post_meta($post_id, '_fl_builder_data_settings', true);

        return new WP_REST_Response([
            'success'   => true,
            'post_id'   => $post_id,
            'enabled'   => (bool) get_post_meta($post_id, '_fl_builder_enabled', true),
            // JSON view: convenient, but LOSSY. JSON cannot express the
            // difference between a PHP array and a stdClass, and BB stores
            // both (settings bags are objects; `border`, `bg_gradient`,
            // font/padding groups are arrays). Use it for inspection only.
            'layout'    => $layout,
            'settings'  => $lsettings,
            // Lossless view: PHP-serialized then base64'd. Round-trip THIS
            // when copying a layout, never the JSON. See v3.2.3 changelog.
            'layout_php'   => $layout ? base64_encode(serialize($layout)) : null,
            'settings_php' => $lsettings ? base64_encode(serialize($lsettings)) : null,
            'bb_active' => class_exists('FLBuilderModel'),
        ], 200);
    }

    public function handle_fl_builder_write($request) {
        $ip = $this->get_client_ip();
        $params = $request->get_json_params() ?? [];
        $post = $this->resolve_post($params);
        if (is_wp_error($post)) {
            $this->audit_log('fl_builder', false, $ip, $post->get_error_message());
            return $post;
        }
        $post_id = $post->ID;

        // PREFERRED PATH: layout_php, base64 of a PHP-serialized array.
        //
        // JSON cannot round-trip BB layouts. Node settings bags are stdClass,
        // but many INDIVIDUAL settings are PHP arrays (`border`,
        // `bg_gradient*`, `*_padding`, `*_margin`, font groups). BB reads those
        // with array syntax, e.g. $settings->border['style'], so handing it a
        // stdClass throws "Cannot use object of type stdClass as array" and
        // kills the request mid-render: the page returns 200 with a truncated
        // <head>, no </body>, no fl-node markup, and BB never writes its
        // layout CSS. It looks exactly like a blank white page.
        //
        // assoc=true makes every object an array; assoc=false makes every array
        // an object. Both are wrong, because the correct answer differs per
        // setting. Only PHP serialization preserves it.
        //
        // allowed_classes is pinned to stdClass: never unserialize arbitrary
        // classes from a request body (object-injection).
        $layout = null;
        if (!empty($params['layout_php'])) {
            $raw = $this->b64_strict($params['layout_php']);
            if ($raw === false) {
                return new WP_Error('bad_request', 'layout_php is not valid base64.',
                    ['status' => 400]);
            }
            $layout = @unserialize($raw, ['allowed_classes' => ['stdClass']]);
            if (!is_array($layout)) {
                return new WP_Error('bad_request',
                    'layout_php did not unserialize to an array.', ['status' => 400]);
            }
        } else {
            $decoded = $this->fl_decode_body($request);
            $layout_obj = ($decoded && isset($decoded->layout)) ? $decoded->layout : null;
            $layout = is_object($layout_obj) ? get_object_vars($layout_obj)
                    : (is_array($layout_obj) ? $layout_obj : null);
        }

        if (!is_array($layout) || empty($layout)) {
            return new WP_Error('bad_request',
                'layout must be a non-empty map of node_id => node.', ['status' => 400]);
        }

        // Every node must carry the fields BB indexes on, or the editor breaks
        // in ways that are hard to trace back to this call.
        foreach ($layout as $node_id => $node) {
            if (!is_object($node) || !isset($node->node, $node->type)) {
                return new WP_Error('bad_request',
                    "node '{$node_id}' is missing 'node' or 'type'.", ['status' => 400]);
            }
            if ($node->node !== $node_id) {
                return new WP_Error('bad_request',
                    "node '{$node_id}' key does not match its node id '{$node->node}'.",
                    ['status' => 400]);
            }
            // BB nodes carry `global` alongside node/type/parent/position/
            // settings. A node without it breaks rendering, so default rather
            // than trust the caller.
            if (!isset($node->global)) {
                $node->global = false;
            }
        }

        // Roll back to this if anything downstream goes wrong.
        $backup = [
            'data'     => get_post_meta($post_id, '_fl_builder_data', true),
            'settings' => get_post_meta($post_id, '_fl_builder_data_settings', true),
            'enabled'  => get_post_meta($post_id, '_fl_builder_enabled', true),
            'content'  => $post->post_content,
        ];
        update_post_meta($post_id, '_sadie_fl_backup', $backup);

        // $layout already holds stdClass nodes from json_decode(..., false);
        // the top level stays a plain array, which is what BB expects.
        $nodes = $layout;

        $settings = (object) ['css' => '', 'js' => ''];
        if (!empty($params['settings_php'])) {
            $rawset = $this->b64_strict($params['settings_php']);
            $maybe = $rawset === false ? false
                   : @unserialize($rawset, ['allowed_classes' => ['stdClass']]);
            if (is_object($maybe)) {
                $settings = $maybe;
            }
        } elseif (isset($decoded) && isset($decoded->settings)
                  && is_object($decoded->settings)) {
            $settings = $decoded->settings;
        }

        // wp_slash before update_post_meta: update_metadata() unslashes, so
        // unslashed CSS/HTML inside settings would lose its backslashes.
        // Pass the real structure (never a pre-serialized string) so WordPress
        // does the serializing itself.
        update_post_meta($post_id, '_fl_builder_data', wp_slash($nodes));
        update_post_meta($post_id, '_fl_builder_draft', wp_slash($nodes));
        update_post_meta($post_id, '_fl_builder_data_settings', wp_slash($settings));
        update_post_meta($post_id, '_fl_builder_draft_settings', wp_slash($settings));

        $enabled = array_key_exists('enabled', $params) ? (bool) $params['enabled'] : true;
        update_post_meta($post_id, '_fl_builder_enabled', $enabled ? 1 : 0);

        // post_content is BB's non-JS fallback and what most SEO crawlers read.
        if (isset($params['content']) && is_string($params['content'])) {
            $content = $params['content'];
            if (strpos($content, 'wp:fl-builder/layout') === false) {
                $content = "<!-- wp:fl-builder/layout -->\n" . $content;
            }
            wp_update_post([
                'ID'           => $post_id,
                'post_content' => wp_slash($content),
            ]);
        }

        $cleared = $this->fl_clear_cache($post_id);

        // Read back and confirm the meta round-tripped as a real array with the
        // node count we sent. A write that "succeeded" but stored a string is
        // the exact failure this endpoint exists to prevent, so never report
        // success without checking. [verification-fail-loud-01]
        $written = get_post_meta($post_id, '_fl_builder_data', true);
        $ok = is_array($written) && count($written) === count($layout);
        if (!$ok) {
            update_post_meta($post_id, '_fl_builder_data', $backup['data']);
            update_post_meta($post_id, '_fl_builder_data_settings', $backup['settings']);
            update_post_meta($post_id, '_fl_builder_enabled', $backup['enabled']);
            $this->audit_log('fl_builder', false, $ip,
                "Verify failed for post {$post_id}; rolled back");
            return new WP_Error('write_failed',
                'Layout did not persist as an array; rolled back.', ['status' => 500]);
        }

        $this->audit_log('fl_builder', true, $ip,
            "Wrote " . count($layout) . " nodes to post {$post_id}");

        return new WP_REST_Response([
            'success'        => true,
            'post_id'        => $post_id,
            'nodes_written'  => count($written),
            'enabled'        => (bool) get_post_meta($post_id, '_fl_builder_enabled', true),
            'content_set'    => isset($params['content']),
            'cache_cleared'  => $cleared,
            'bb_active'      => class_exists('FLBuilderModel'),
            'backup_meta'    => '_sadie_fl_backup',
        ], 200);
    }

    public function handle_schema($request) {
        $ip = $this->get_client_ip();
        $params = $request->get_json_params() ?? [];
        $post = $this->resolve_post($params);
        if (is_wp_error($post)) {
            $this->audit_log('schema', false, $ip, $post->get_error_message());
            return $post;
        }
        $action = $params['action'] ?? 'set';
        if ($action === 'clear') {
            delete_post_meta($post->ID, '_sadie_schema');
            $this->audit_log('schema', true, $ip, "Cleared schema for post {$post->ID}");
            return new WP_REST_Response(['success' => true, 'action' => 'clear', 'post_id' => $post->ID], 200);
        }

        $raw = $params['schema_json'] ?? null;
        // Accept either a JSON string or a decoded array/object.
        if (is_string($raw)) {
            $decoded = json_decode($raw, true);
        } else {
            $decoded = $raw;
        }
        if (!is_array($decoded) && !is_object($decoded)) {
            return new WP_Error('bad_request', 'schema_json must be a JSON object/array.', ['status' => 400]);
        }
        // Must contain an @type or be an array of typed objects.
        $hasType = false;
        if (is_array($decoded) && isset($decoded['@type'])) {
            $hasType = true;
        } elseif (is_array($decoded)) {
            foreach ($decoded as $d) {
                if (is_array($d) && isset($d['@type'])) { $hasType = true; break; }
            }
        }
        if (!$hasType) {
            return new WP_Error('bad_request', 'schema_json must include an @type (or be a graph of typed objects).', ['status' => 400]);
        }

        $clean = wp_json_encode($decoded, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        update_post_meta($post->ID, '_sadie_schema', $clean);
        $this->audit_log('schema', true, $ip, "Set schema on post {$post->ID}");

        return new WP_REST_Response([
            'success' => true,
            'action' => 'set',
            'post_id' => $post->ID,
            'url' => get_permalink($post->ID),
            'hash' => hash('sha256', $clean),
        ], 200);
    }

