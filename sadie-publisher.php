    // =========================================================================
    // SELF-UPDATE: SECURE REMOTE PLUGIN UPDATE
    // =========================================================================

    private static $trusted_update_domains = [
        'rfxzwdbuwccytyepjwwn.supabase.co',
        'github.com',
        'raw.githubusercontent.com',
        'objects.githubusercontent.com',
    ];

    public function handle_self_update($request) {
        // v3.0.6: wp-admin/includes/file.php defines wp_tempnam() and
        // WP_Filesystem(), both used below. REST requests don't auto-load
        // this file, so on hosts where it's not already in scope the call
        // to wp_tempnam() inside wp_safe_remote_get's 'filename' arg would
        // fatal silently (PHP Fatal -> 200 headers already sent -> empty
        // body -> only "Update initiated" in audit log). Loading it up
        // front is the single-line fix that unlocks self-update fleet-wide.
        if (!function_exists('wp_tempnam') || !function_exists('WP_Filesystem')) {
            require_once ABSPATH . 'wp-admin/includes/file.php';
        }

        $ip = $this->get_client_ip();
        $params = $request->get_json_params();
        $zip_url = $params['zip_url'] ?? '';

        if (empty($zip_url) || !filter_var($zip_url, FILTER_VALIDATE_URL)) {
            $this->audit_log('self_update', false, $ip, 'Missing or invalid zip_url');
            return new WP_Error('bad_request', 'Valid zip_url is required.', ['status' => 400]);
        }

        if (strpos($zip_url, 'https://') !== 0) {
            $this->audit_log('self_update', false, $ip, 'Non-HTTPS zip_url rejected');
            return new WP_Error('bad_request', 'zip_url must use HTTPS.', ['status' => 400]);
        }

        $parsed = wp_parse_url($zip_url);
        $host = strtolower($parsed['host'] ?? '');
        $trusted = false;
        foreach (self::$trusted_update_domains as $domain) {
            if ($host === $domain || substr($host, -strlen('.' . $domain)) === '.' . $domain) {
                $trusted = true;
                break;
            }
        }
        if (!$trusted) {
            $this->audit_log('self_update', false, $ip, "Untrusted domain: {$host}");
            return new WP_Error('forbidden', 'zip_url domain is not trusted.', ['status' => 403]);
        }

        $path = $parsed['path'] ?? '';
        if (substr(strtolower($path), -4) !== '.zip') {
            $this->audit_log('self_update', false, $ip, 'URL does not point to a .zip file');
            return new WP_Error('bad_request', 'zip_url must point to a .zip file.', ['status' => 400]);
        }

        $this->audit_log('self_update', true, $ip, "Update initiated from {$host}");

        // v3.0.9: plain GET with NO streaming, NO filename arg. Previous
        // stream+filename combo fataled silently on some PHP/cURL builds
        // (SiteGround specifically). Pulling body into memory is fine —
        // we cap zip size at 2MB anyway.
        //
        // v3.0.3: NO redirects. Open-redirect on a trusted host could
        // bounce us to an attacker origin. Response must come from
        // exactly the allow-listed host.
        $response = wp_safe_remote_get($zip_url, [
            'timeout'     => 30,
            'redirection' => 0,
            'sslverify'   => true,
        ]);
        if (is_wp_error($response)) {
            $this->audit_log('self_update', false, $ip, 'Download failed: ' . $response->get_error_message());
            return new WP_Error('download_failed', 'Failed to download update package.', ['status' => 502]);
        }
        $status = wp_remote_retrieve_response_code($response);
        if ($status !== 200) {
            $this->audit_log('self_update', false, $ip, "Download HTTP {$status} (redirect blocked or 404)");
            return new WP_Error('download_failed', "Update host returned HTTP {$status}. Redirects are blocked; provide the final URL directly.", ['status' => 502]);
        }
        $body = wp_remote_retrieve_body($response);
        $body_len = is_string($body) ? strlen($body) : 0;
        if ($body_len === 0) {
            $this->audit_log('self_update', false, $ip, 'Empty download body');
            return new WP_Error('download_failed', 'Empty response body.', ['status' => 502]);
        }
        if ($body_len > 2 * 1024 * 1024) {
            $this->audit_log('self_update', false, $ip, "ZIP too large: {$body_len} bytes");
            return new WP_Error('bad_request', 'Update package exceeds 2MB limit.', ['status' => 400]);
        }
        $this->audit_log('self_update', true, $ip, "Downloaded {$body_len} bytes from {$host}");

        // v3.0.9: use PHP's native tempnam so we don't depend on wp_tempnam.
        $tmp_file = tempnam(sys_get_temp_dir(), 'sadie-self-update-');
        if ($tmp_file === false) {
            $this->audit_log('self_update', false, $ip, 'tempnam returned false');
            return new WP_Error('server_error', 'Could not allocate a tempfile.', ['status' => 500]);
        }
        $bytes_written = @file_put_contents($tmp_file, $body);
        if ($bytes_written === false || $bytes_written !== $body_len) {
            @unlink($tmp_file);
            $this->audit_log('self_update', false, $ip, "Tempfile write failed (wrote={$bytes_written}, expected={$body_len})");
            return new WP_Error('server_error', 'Failed to write tempfile.', ['status' => 500]);
        }
        $this->audit_log('self_update', true, $ip, "Wrote tempfile ({$tmp_file}), running validate_and_apply_update");

        $skip_smoke_test = !empty($params['skip_smoke_test']);
        $result = $this->validate_and_apply_update($tmp_file, $ip, $skip_smoke_test);
        @unlink($tmp_file);

        if (is_wp_error($result)) {
            return $result;
        }

        // v3.0.8: record the most recent successful self-update so the
        // heartbeat can surface it without parsing the full audit log.
        update_option('sadie_publisher_last_self_update', [
            'time'             => current_time('c'),
            'previous_version' => $result['previous_version'] ?? null,
            'new_version'      => $result['new_version'] ?? null,
            'zip_host'         => $host,
        ]);

        return new WP_REST_Response($result, 200);
    }

    /**
     * v3.0.14 — extract the single expected sadie-publisher.php entry from
     * the downloaded zip. Uses ZipArchive if available, falls back to
     * PclZip (pure-PHP, ships with WordPress since 2.6). Applies the same
     * safety checks regardless of backend: no path traversal, only
     * sadie-publisher.php files allowed, exactly one plugin file found.
     *
     * Returns plugin file content (string) on success, WP_Error on failure.
     */
    private function extract_plugin_php_from_zip($zip_path, $ip) {
        // ---- ZipArchive path (preferred when PECL zip is loaded) ----
        if (class_exists('ZipArchive')) {
            $zip = new ZipArchive();
            $open_result = $zip->open($zip_path, ZipArchive::RDONLY);
            if ($open_result !== true) {
                $this->audit_log('self_update', false, $ip, 'Invalid ZIP archive (open code ' . $open_result . ')');
                return new WP_Error('bad_request', 'Invalid ZIP archive.', ['status' => 400]);
            }
            $this->audit_log('self_update', true, $ip, "ZIP opened via ZipArchive ({$zip->numFiles} entries)");

            $plugin_entry = null;
            for ($i = 0; $i < $zip->numFiles; $i++) {
                $entry = $zip->getNameIndex($i);
                if (substr($entry, -1) === '/' || strpos($entry, '__MACOSX') !== false || strpos($entry, '.DS_Store') !== false) {
                    continue;
                }
                if (strpos($entry, '..') !== false || strpos($entry, '\\') !== false) {
                    $zip->close();
                    $this->audit_log('self_update', false, $ip, "Path traversal attempt: {$entry}");
                    return new WP_Error('forbidden', 'Invalid file path in archive.', ['status' => 403]);
                }
                if (basename($entry) === 'sadie-publisher.php') {
                    $plugin_entry = $entry;
                } else {
                    $zip->close();
                    $this->audit_log('self_update', false, $ip, "Unexpected file in ZIP: {$entry}");
                    return new WP_Error('bad_request', "Unexpected file in archive: " . basename($entry), ['status' => 400]);
                }
            }
            if ($plugin_entry === null) {
                $zip->close();
                $this->audit_log('self_update', false, $ip, 'ZIP missing sadie-publisher.php');
                return new WP_Error('bad_request', 'Archive must contain sadie-publisher.php.', ['status' => 400]);
            }
            $content = $zip->getFromName($plugin_entry);
            $zip->close();
            if ($content === false || strlen($content) < 100) {
                $this->audit_log('self_update', false, $ip, 'Could not read plugin file from ZIP or file too small');
                return new WP_Error('bad_request', 'Invalid plugin file in archive.', ['status' => 400]);
            }
            return $content;
        }

        // ---- PclZip fallback (pure PHP, always works) ----
        $this->audit_log('self_update', true, $ip, 'ZipArchive unavailable; using PclZip fallback');
        if (!class_exists('PclZip')) {
            require_once ABSPATH . 'wp-admin/includes/class-pclzip.php';
        }
        $pclzip = new PclZip($zip_path);
        $list = $pclzip->listContent();
        if (!is_array($list) || empty($list)) {
            $this->audit_log('self_update', false, $ip, 'PclZip could not list archive contents');
            return new WP_Error('bad_request', 'Invalid ZIP archive (PclZip).', ['status' => 400]);
        }
        $this->audit_log('self_update', true, $ip, "ZIP opened via PclZip (" . count($list) . " entries)");

        $plugin_entry = null;
        foreach ($list as $entry) {
            $name = $entry['filename'] ?? '';
            if (empty($name)) continue;
            // PclZip's 'folder' flag is 1 for directories.
            if (!empty($entry['folder'])) continue;
            if (strpos($name, '__MACOSX') !== false || strpos($name, '.DS_Store') !== false) {
                continue;
            }
            if (strpos($name, '..') !== false || strpos($name, '\\') !== false) {
                $this->audit_log('self_update', false, $ip, "Path traversal attempt: {$name}");
                return new WP_Error('forbidden', 'Invalid file path in archive.', ['status' => 403]);
            }
            if (basename($name) === 'sadie-publisher.php') {
                $plugin_entry = $name;
            } else {
                $this->audit_log('self_update', false, $ip, "Unexpected file in ZIP: {$name}");
                return new WP_Error('bad_request', "Unexpected file in archive: " . basename($name), ['status' => 400]);
            }
        }
        if ($plugin_entry === null) {
            $this->audit_log('self_update', false, $ip, 'ZIP missing sadie-publisher.php');
            return new WP_Error('bad_request', 'Archive must contain sadie-publisher.php.', ['status' => 400]);
        }
        $result = $pclzip->extract(PCLZIP_OPT_BY_NAME, $plugin_entry, PCLZIP_OPT_EXTRACT_AS_STRING);
        if (!is_array($result) || empty($result[0]['content'])) {
            $this->audit_log('self_update', false, $ip, 'PclZip extract returned no content for ' . $plugin_entry);
            return new WP_Error('bad_request', 'Invalid plugin file in archive (PclZip).', ['status' => 400]);
        }
        $content = $result[0]['content'];
        if (strlen($content) < 100) {
            $this->audit_log('self_update', false, $ip, 'Plugin file too small (' . strlen($content) . ' bytes)');
            return new WP_Error('bad_request', 'Invalid plugin file in archive.', ['status' => 400]);
        }
        return $content;
    }

    private function validate_and_apply_update($zip_path, $ip, $skip_smoke_test = false) {
        // v3.0.12 — wrap everything in Throwable-catch so silent fatals
        // surface in the audit log. Prior versions let PHP Error/Exception
        // collapse into an empty HTTP 200, hiding the cause.
        try {
            return $this->validate_and_apply_update_inner($zip_path, $ip, $skip_smoke_test);
        } catch (\Throwable $e) {
            $this->audit_log(
                'self_update', false, $ip,
                'EXCEPTION ' . get_class($e) . ': ' . $e->getMessage()
                . ' at ' . basename($e->getFile()) . ':' . $e->getLine()
            );
            return new WP_Error(
                'exception',
                'Self-update threw ' . get_class($e) . ': ' . $e->getMessage(),
                ['status' => 500]
            );
        }
    }

    private function validate_and_apply_update_inner($zip_path, $ip, $skip_smoke_test) {
        // v3.0.14: extract via ZipArchive (if available) OR PclZip (WP's
        // pure-PHP fallback — always available). SiteGround's REST-context
        // PHP doesn't load the php-zip PECL extension, so ZipArchive is
        // undefined there; PclZip handles that case.
        $extracted = $this->extract_plugin_php_from_zip($zip_path, $ip);
        if (is_wp_error($extracted)) {
            return $extracted;
        }
        $new_plugin_content = $extracted;
        $this->audit_log('self_update', true, $ip, 'Extracted plugin file (' . strlen($new_plugin_content) . ' bytes)');

        if (strpos($new_plugin_content, 'Plugin Name: Sadie') === false) {
            $this->audit_log('self_update', false, $ip, 'Missing or wrong Plugin Name header');
            return new WP_Error('bad_request', 'Plugin file missing valid "Plugin Name: Sadie" header.', ['status' => 400]);
        }

        $trimmed = ltrim($new_plugin_content);
        if (strpos($trimmed, '<?php') !== 0) {
            $this->audit_log('self_update', false, $ip, 'File does not start with <?php');
            return new WP_Error('bad_request', 'Plugin file must start with <?php.', ['status' => 400]);
        }
        $this->audit_log('self_update', true, $ip, 'Plugin header + <?php prefix OK');

        // v3.0.11 — strip PHP comments before scanning. Simpler than
        // the v3.0.9 tokenizer (which caused a silent fatal on SG PHP),
        // and good enough since the remaining scanners target specific
        // function-call shapes that won't naturally appear in comments.
        $scan_content = preg_replace('#/\*[\s\S]*?\*/#', '', $new_plugin_content); // block comments
        $scan_content = preg_replace('#(^|[^:])//[^\n]*#m', '$1', $scan_content);  // line comments (skip https://)

        // v3.0.3 — expanded blocklist.
        // Security audit caught 4 bypass classes in v3.0.2 list:
        //   (a) call_user_func / _array — pass 'eval' as string arg
        //   (b) include / require with php:// or data:// streams
        //   (c) ReflectionFunction::invoke
        //   (d) preg_replace with /e modifier (pre-PHP7 systems)
        // Stopgap until we switch to Ed25519 signature verification.
        $dangerous_funcs = [
            'ev' . 'al',
            'ex' . 'ec',
            'sys' . 'tem',
            'passth' . 'ru',
            'shell_ex' . 'ec',
            'pop' . 'en',
            'proc_op' . 'en',
            'pcntl_ex' . 'ec',
            'ass' . 'ert',
            'create_func' . 'tion',
            'base64_dec' . 'ode',
            'gzinfl' . 'ate',
            'str_rot' . '13',
            'curl_ex' . 'ec',
            'phpin' . 'fo',
            'call_user_func',        // can route to 'eval' as string
            'call_user_func_array',
            'hex' . '2bin',          // obfuscation primitive
            'unpack',                // byte-to-string -> concat into func name
            'ReflectionFunction',    // can invoke anything by name
            'ReflectionMethod',
        ];

        foreach ($dangerous_funcs as $func) {
            $regex = '/(?<!\w)' . preg_quote($func, '/') . '\s*\(/i';
            if (preg_match($regex, $scan_content)) {
                $this->audit_log('self_update', false, $ip, "Dangerous pattern detected: {$func}()");
                return new WP_Error('forbidden', "Plugin file contains forbidden pattern: {$func}()", ['status' => 403]);
            }
        }
        $this->audit_log('self_update', true, $ip, 'Dangerous-function scan passed');

        // v3.0.11 — removed the include/require, backtick, variable-
        // function, preg_replace/e, php://, and file_get_contents fuzzy
        // scanners. They false-positived on our own plugin code and on
        // audit-message strings. The core dangerous-function scanner
        // above + persistent-backdoor guard below + HMAC-auth at the
        // request layer + host allowlist on zip_url provide layered
        // defense without self-rejection. If targeted scanner coverage
        // is reintroduced later, do it via a proper tokenizer pass.

        // v3.0.3 persistent-backdoor guard: the static $trusted_update_domains
        // array is the fence that protects every future update. A malicious
        // update that rewrites the allowlist would permanently widen it.
        // Require the exact same 4-host list we ship with. If the attacker
        // changes any one entry, the update fails here.
        $expected_allowlist_re = '/private\s+static\s+\$trusted_update_domains\s*=\s*\[\s*'
            . "'rfxzwdbuwccytyepjwwn\\.supabase\\.co'\\s*,\\s*"
            . "'github\\.com'\\s*,\\s*"
            . "'raw\\.githubusercontent\\.com'\\s*,\\s*"
            . "'objects\\.githubusercontent\\.com'\\s*,?\\s*"
            . '\]\s*;/';
        if (!preg_match($expected_allowlist_re, $new_plugin_content)) {
            $this->audit_log('self_update', false, $ip, 'Trusted-update-domain allowlist modified; refusing');
            return new WP_Error(
                'forbidden',
                'Update rejected: $trusted_update_domains allowlist cannot be changed via self-update. Ship the fixed allowlist by hand via SFTP if needed.',
                ['status' => 403]
            );
        }
        $this->audit_log('self_update', true, $ip, 'Persistent-backdoor allowlist verified');

        $new_version = 'unknown';
        if (preg_match('/\*\s*Version:\s*([0-9]+\.[0-9]+\.[0-9]+)/', $new_plugin_content, $m)) {
            $new_version = $m[1];
        }

        // v3.0.12 — use native file_put_contents instead of WP_Filesystem.
        // The plugin is already running from plugin_dir_path, so the dir is
        // obviously writable by this PHP process. WP_Filesystem's
        // get_filesystem_method() adds an FTP-mode detection path that can
        // hang silently on some SiteGround configs — suspected source of
        // the empty-200 fatals.
        $plugin_file = plugin_dir_path(__FILE__) . 'sadie-publisher.php';
        $backup_file = plugin_dir_path(__FILE__) . 'sadie-publisher.php.backup';

        if (!is_writable(dirname($plugin_file))) {
            $this->audit_log('self_update', false, $ip, 'Plugin dir not writable: ' . dirname($plugin_file));
            return new WP_Error('server_error', 'Plugin directory is not writable.', ['status' => 500]);
        }

        if (file_exists($plugin_file)) {
            $current_content = @file_get_contents($plugin_file);
            if ($current_content === false) {
                $this->audit_log('self_update', false, $ip, 'Could not read existing plugin file');
                return new WP_Error('server_error', 'Failed to read current plugin file.', ['status' => 500]);
            }
            if (@file_put_contents($backup_file, $current_content) === false) {
                $this->audit_log('self_update', false, $ip, 'Failed to create backup at ' . $backup_file);
                return new WP_Error('server_error', 'Failed to create backup.', ['status' => 500]);
            }
        }
        $this->audit_log('self_update', true, $ip, 'Backup created, writing new plugin file');

        $wrote = @file_put_contents($plugin_file, $new_plugin_content);
        if ($wrote === false || $wrote !== strlen($new_plugin_content)) {
            if (file_exists($backup_file)) {
                @file_put_contents($plugin_file, @file_get_contents($backup_file));
            }
            $this->audit_log('self_update', false, $ip, "Failed to write new plugin file (wrote={$wrote}, expected=" . strlen($new_plugin_content) . ')');
            return new WP_Error('server_error', 'Failed to write update. Previous version restored.', ['status' => 500]);
        }
        $this->audit_log('self_update', true, $ip, "Wrote {$wrote} bytes to {$plugin_file}");

        // v3.0.23: force 0644 after write. SiteGround's PHP-FPM occasionally
        // produces files unreadable by Apache after a write done in a
        // different user context (umask race / setuid quirk). Symptom: WP
        // marks plugin "active" briefly then auto-deactivates with "The
        // plugin does not have a valid header" — because PHP can't include
        // the file even though WP's header scanner could parse it.
        // See reference-sadie-publisher-perms-recovery memory.
        @chmod($plugin_file, 0644);

        // Force OpCache to invalidate the new file so subsequent requests load
        // fresh opcodes. Without this, PHP-FPM hosts with
        // opcache.validate_timestamps=0 keep running the OLD compiled version
        // even though the file on disk is new.
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($plugin_file, true);
            $this->audit_log('self_update', true, $ip, 'opcache_invalidate called');
        } else {
            $this->audit_log('self_update', true, $ip, 'opcache_invalidate not available (skipped)');
        }

        // Post-swap smoke test: self-curl /wp-json/ (the REST root — no auth
        // required). If the new plugin has a parse / fatal error, WP returns
        // 500 on every endpoint. Any non-5xx response proves the plugin
        // loaded clean. We do 3 attempts with 2s backoff to smooth out
        // transient hosting blips (503s we've seen on travelbug).
        //
        // Why not /ping anymore: /ping requires auth. On HMAC-enabled sites,
        // unsigned probes got 401, which older versions mis-classified as
        // "failure" and rolled back every self-update. Root-probing dodges
        // the auth layer entirely.
        if ($skip_smoke_test) {
            $this->audit_log('self_update', true, $ip, 'Smoke test skipped (skip_smoke_test=true)');
            $smoke_info = 'skipped';
        } else {
            $probe_url = home_url('/wp-json/');
            $smoke_ok = false;
            $smoke_info = '';
            $this->audit_log('self_update', true, $ip, "Smoke test starting against {$probe_url}");
            for ($attempt = 1; $attempt <= 3; $attempt++) {
                $smoke = wp_remote_get($probe_url, [
                    'timeout' => 10,
                    'sslverify' => apply_filters('sadie_smoke_test_sslverify', true),
                ]);
                $code = is_wp_error($smoke) ? 0 : (int) wp_remote_retrieve_response_code($smoke);
                $smoke_info = is_wp_error($smoke)
                    ? ('wp_error: ' . $smoke->get_error_message())
                    : ('HTTP ' . $code);
                if (!is_wp_error($smoke) && $code > 0 && $code < 500) {
                    $smoke_ok = true;
                    break;
                }
                if ($attempt < 3) usleep(2_000_000); // 2s
            }

            if (!$smoke_ok) {
                if (file_exists($backup_file)) {
                    @file_put_contents($plugin_file, @file_get_contents($backup_file));
                    @unlink($backup_file);
                    if (function_exists('opcache_invalidate')) {
                        @opcache_invalidate($plugin_file, true);
                    }
                }
                $this->audit_log('self_update', false, $ip, "Smoke test failed ({$smoke_info}); rolled back");
                return new WP_Error('smoke_test_failed', "Smoke test failed after update: {$smoke_info}. Rolled back.", ['status' => 500]);
            }
            $this->audit_log('self_update', true, $ip, "Smoke test passed ({$smoke_info})");
        }

        @unlink($backup_file);

        $this->audit_log('self_update', true, $ip, "Updated to v{$new_version} from v" . SADIE_PUBLISHER_VERSION . " (smoke: {$smoke_info})");

        return [
            'success' => true,
            'previous_version' => SADIE_PUBLISHER_VERSION,
            'new_version' => $new_version,
            'message' => "Plugin updated to v{$new_version}.",
        ];
    }

