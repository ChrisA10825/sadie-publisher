    /**
     * v3.0.23: GET /internal-link-graph/summary
     *
     * Reads RankMath's wp_rank_math_internal_meta (per-post counts) and joins
     * post_title/post_type/post_status from wp_posts so callers can rank pages
     * by inbound-internal-link count without a second round trip.
     *
     * Query params (all optional):
     *   post_type        comma-separated list, default "post,page"
     *   post_status      default "publish"
     *   max_incoming     filter: only posts with incoming_link_count <= this
     *   min_incoming     filter: only posts with incoming_link_count >= this
     *   order            "incoming.asc" (default) | "incoming.desc" |
     *                    "internal.asc" | "internal.desc"
     *   limit            default 500, hard-capped at 2000
     *
     * Counts come straight from RankMath; we do not recompute. If the module
     * is disabled the table will be empty (not missing). Missing table → 412.
     */
    public function handle_link_graph_summary($request) {
        global $wpdb;
        $meta_table = $wpdb->prefix . 'rank_math_internal_meta';
        $exists = $wpdb->get_var($wpdb->prepare("SHOW TABLES LIKE %s", $meta_table));
        if ($exists !== $meta_table) {
            return new WP_Error(
                'rankmath_missing',
                'wp_rank_math_internal_meta not found. Is RankMath active and the Link Counter module enabled?',
                ['status' => 412]
            );
        }

        $post_type   = $request->get_param('post_type') ?: 'post,page';
        $post_status = $request->get_param('post_status') ?: 'publish';
        $max_in      = $request->get_param('max_incoming');
        $min_in      = $request->get_param('min_incoming');
        $order_in    = $request->get_param('order') ?: 'incoming.asc';
        $limit       = (int) ($request->get_param('limit') ?: 500);
        if ($limit < 1) { $limit = 1; }
        if ($limit > 2000) { $limit = 2000; }

        // Sanitize post_type / post_status into prepared placeholders
        $types = array_filter(array_map('sanitize_key', array_map('trim', explode(',', $post_type))));
        if (empty($types)) { $types = ['post', 'page']; }
        $statuses = array_filter(array_map('sanitize_key', array_map('trim', explode(',', $post_status))));
        if (empty($statuses)) { $statuses = ['publish']; }

        $type_ph   = implode(',', array_fill(0, count($types), '%s'));
        $status_ph = implode(',', array_fill(0, count($statuses), '%s'));

        // Whitelist order
        $order_map = [
            'incoming.asc'  => 'm.incoming_link_count ASC',
            'incoming.desc' => 'm.incoming_link_count DESC',
            'internal.asc'  => 'm.internal_link_count ASC',
            'internal.desc' => 'm.internal_link_count DESC',
        ];
        $order_sql = $order_map[$order_in] ?? $order_map['incoming.asc'];

        $where  = "p.post_type IN ($type_ph) AND p.post_status IN ($status_ph)";
        $params = array_merge($types, $statuses);

        if ($min_in !== null && $min_in !== '') {
            $where   .= " AND m.incoming_link_count >= %d";
            $params[] = (int) $min_in;
        }
        if ($max_in !== null && $max_in !== '') {
            $where   .= " AND m.incoming_link_count <= %d";
            $params[] = (int) $max_in;
        }

        $params[] = $limit;

        $sql = "SELECT
                    p.ID                       AS post_id,
                    p.post_title               AS post_title,
                    p.post_name                AS slug,
                    p.post_type                AS post_type,
                    p.post_status              AS post_status,
                    p.post_date                AS post_date,
                    COALESCE(m.internal_link_count, 0) AS outgoing_internal,
                    COALESCE(m.external_link_count, 0) AS outgoing_external,
                    COALESCE(m.incoming_link_count, 0) AS incoming_internal
                FROM {$wpdb->posts} p
                LEFT JOIN {$meta_table} m
                  ON m.object_id = p.ID
                WHERE $where
                ORDER BY $order_sql, p.ID ASC
                LIMIT %d";

        $rows = $wpdb->get_results($wpdb->prepare($sql, $params), ARRAY_A);

        // Attach permalink to each row (cheap, in-process)
        foreach ($rows as &$r) {
            $r['permalink'] = get_permalink((int) $r['post_id']);
            // ints in JSON, not strings
            foreach (['post_id', 'outgoing_internal', 'outgoing_external', 'incoming_internal'] as $k) {
                $r[$k] = (int) $r[$k];
            }
        }

        $this->audit_log('link_graph_summary', true, $this->get_client_ip(), count($rows) . ' rows');
        return new WP_REST_Response([
            'success'        => true,
            'count'          => count($rows),
            'limit_applied'  => $limit,
            'rows'           => $rows,
            'rankmath_table' => $meta_table,
        ], 200);
    }

    /**
     * v3.0.23: GET /internal-link-graph/edges
     *
     * Reads RankMath's wp_rank_math_internal_links edge table.
     * Use to find what links INTO a target or OUT FROM a source.
     *
     * Query params (all optional):
     *   source_post_id   filter on the post that contains the link
     *   target_post_id   filter on the linked-to post (internal links only)
     *   type             default "internal" (also: external,img,internal,iframe,*)
     *                    pass "*" to skip the filter
     *   limit            default 1000, hard-capped at 5000
