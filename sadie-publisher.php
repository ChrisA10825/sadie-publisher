    /**
     * POST /sadie-publisher/v1/headings
     *
     * Body:
     *   { post_id|slug|url, h1?: string, h2_replacements?: [{old, new}, ...] }
     *
     * H1: when present, replaces post_title (which most WP themes render as
     *     the page's H1). The old title is stashed at _sadie_h1_backup so
     *     rollback is a simple restore.
     *
     * H2: optional array of old→new rewrites inside post_content. We match
     *     the exact H2 inner-text (case-insensitive, whitespace-collapsed)
     *     and replace it in-place — leaving surrounding markup untouched.
     *     An empty "new" unwraps the H2 (removes heading, keeps text).
     */
    public function handle_headings($request) {
        $ip = $this->get_client_ip();
        $body = $request->get_json_params();

        $post = $this->resolve_post($body);
        if (is_wp_error($post)) {
            return $post;
        }

        $updated = [];
        $skipped = [];

        // ── H1 (post_title) ────────────────────────────────────────────────
        if (isset($body['h1']) && is_string($body['h1']) && trim($body['h1']) !== '') {
            // v3.0.21: always sanitize heading text before write
            $new_h1 = sanitize_text_field(self::sanitize_heading_title($body['h1']));
            if ($new_h1 !== $post->post_title) {
                // Backup current title once so rollback is deterministic
                if (!get_post_meta($post->ID, '_sadie_h1_backup', true)) {
                    update_post_meta($post->ID, '_sadie_h1_backup', $post->post_title);
                }
                $result = wp_update_post([
                    'ID' => $post->ID,
                    'post_title' => $new_h1,
                ], true);
                if (is_wp_error($result)) {
                    return new WP_Error('h1_update_failed', $result->get_error_message(), ['status' => 500]);
                }
                $updated['h1'] = ['old' => $post->post_title, 'new' => $new_h1];
            } else {
                $skipped['h1'] = 'unchanged';
            }
        }

        // ── H2 replacements ────────────────────────────────────────────────
        $h2_ops = $body['h2_replacements'] ?? [];
        if (is_array($h2_ops) && !empty($h2_ops)) {
            $content = $post->post_content;
            $original = $content;
            $h2_results = [];

            foreach ($h2_ops as $op) {
                $old = isset($op['old']) ? (string) $op['old'] : '';
                $new = isset($op['new']) ? (string) $op['new'] : '';
                if ($old === '') {
                    $h2_results[] = ['old' => $old, 'new' => $new, 'status' => 'bad_request'];
                    continue;
                }

                // Match any <h2 ...>old</h2> (case-insensitive, whitespace-tolerant).
                // Escape regex metacharacters in $old but keep flexibility for
                // internal whitespace variance.
                $escaped = preg_quote(trim($old), '/');
                $escaped = preg_replace('/\s+/', '\s+', $escaped);
                $pattern = '/(<h2\b[^>]*>)\s*' . $escaped . '\s*(<\/h2>)/i';

                if (trim($new) === '') {
                    // Unwrap: remove the <h2> entirely (including text).
                    $replacement = '';
                } else {
                    // v3.0.21: always sanitize heading text before write
                    $replacement = '$1' . esc_html(self::sanitize_heading_title($new)) . '$2';
                }
                $count = 0;
                $content = preg_replace($pattern, $replacement, $content, 1, $count);
                $h2_results[] = [
                    'old' => $old,
                    'new' => $new,
                    'matched' => $count,
                ];
            }

            if ($content !== $original) {
                // Backup previous content (once per post) for rollback.
                if (!get_post_meta($post->ID, '_sadie_h2_backup', true)) {
                    update_post_meta($post->ID, '_sadie_h2_backup', $original);
                }
                $result = wp_update_post([
                    'ID' => $post->ID,
                    'post_content' => $content,
                ], true);
                if (is_wp_error($result)) {
                    return new WP_Error('h2_update_failed', $result->get_error_message(), ['status' => 500]);
                }
                $updated['h2_replacements'] = $h2_results;
            } else {
                $skipped['h2_replacements'] = $h2_results;
            }
        }

        $this->audit_log('headings', true, $ip, "Updated headings on post #{$post->ID}");

        return new WP_REST_Response([
            'success' => true,
            'post_id' => $post->ID,
            'url' => get_permalink($post->ID),
            'updated' => $updated,
            'skipped' => $skipped,
        ], 200);
    }

    /**
     * Resolve a WP_Post from { post_id, slug, or url }.
     */
    private function resolve_post($params) {
        // By explicit post_id
        if (!empty($params['post_id'])) {
            $post = get_post(absint($params['post_id']));
            if (!$post) {
                return new WP_Error('not_found', "Post #{$params['post_id']} not found.", ['status' => 404]);
            }
            return $post;
        }

        // By slug
        if (!empty($params['slug'])) {
            $slug = sanitize_title($params['slug']);
            // Search posts and pages
            $posts = get_posts([
                'name' => $slug,
                'post_type' => ['post', 'page', 'product'],
                'post_status' => ['publish', 'draft', 'private'],
                'numberposts' => 1,
            ]);
            if (empty($posts)) {
                return new WP_Error('not_found', "No post found with slug '{$slug}'.", ['status' => 404]);
            }
            return $posts[0];
        }

        // By URL — resolve to an editable WP_Post via this order:
        //   1. url_to_postid() — standalone pages/posts/products
        //   2. page_for_posts — WP "Posts page" (Reading settings), e.g. /blog/
        //      as a real editable Page whose permalink WP routes as the blog index
        //   3. page_on_front — static front page (Reading settings)
        //   4. Slug fallback — but only when the candidate's permalink equals
        //      the submitted URL (prevents writing to a random same-slug post)
        //   5. Archive blocklist — only for true taxonomy/author/pagination URLs
        //
        // v3.0.19: removed blanket /blog/ rejection. /blog/ is commonly a real
        // editable Page (posts page); handled via page_for_posts above. Slug
        // fallback's permalink check is enough to prevent wrong-post writes
        // when there's no backing page.
        if (!empty($params['url'])) {
            $url = esc_url_raw($params['url']);
            $post_id = url_to_postid($url);
            if ($post_id) {
                return get_post($post_id);
            }

            $normalized_url = rtrim($url, '/');

            $posts_page_id = (int) get_option('page_for_posts');
            if ($posts_page_id) {
                $posts_page_url = get_permalink($posts_page_id);
                if ($posts_page_url && rtrim($posts_page_url, '/') === $normalized_url) {
                    return get_post($posts_page_id);
                }
            }

            $front_page_id = (int) get_option('page_on_front');
            if ($front_page_id && (string) get_option('show_on_front') === 'page') {
                $front_page_url = get_permalink($front_page_id);
                if ($front_page_url && rtrim($front_page_url, '/') === $normalized_url) {
                    return get_post($front_page_id);
                }
            }

            $path = trim(wp_parse_url($url, PHP_URL_PATH), '/');
            $segments = $path === '' ? [] : explode('/', $path);
            $slug = !empty($segments) ? end($segments) : '';
            if ($slug) {
                $posts = get_posts([
                    'name' => sanitize_title($slug),
                    'post_type' => ['post', 'page', 'product'],
                    'post_status' => ['publish', 'draft', 'private'],
                    'numberposts' => 5,
                ]);
                foreach ($posts as $candidate) {
                    $cand_url = get_permalink($candidate->ID);
                    if ($cand_url && rtrim($cand_url, '/') === $normalized_url) {
                        return $candidate;
                    }
                }
            }

            // True archives: taxonomy/author listings + paginated listings + home.
            $archive_prefixes = ['category', 'tag', 'author', 'page'];
            $first_segment = $segments[0] ?? '';
            $is_archive = $path === '' || in_array($first_segment, $archive_prefixes, true);
            if ($is_archive) {
                return new WP_Error(
                    'archive_url',
                    "URL '{$url}' is an archive/listing page with no editable post_id. Update the theme/Yoast archive settings directly.",
                    ['status' => 400]
                );
            }

            return new WP_Error('not_found', "No post found for URL '{$url}'.", ['status' => 404]);
        }

        return new WP_Error('bad_request', 'Provide post_id, slug, or url.', ['status' => 400]);
    }

    /**
     * Apply SEO meta fields to a post. Returns list of fields that were updated.
     */
    private function apply_seo_meta($post_id, $fields) {
        $updated = [];

        // Standard SEO fields — delegate to existing set_seo_meta
        $seo_fields = [];
        foreach (['meta_title', 'meta_description', 'focus_keyword', 'canonical_url', 'og_title', 'og_description', 'schema'] as $key) {
            if (isset($fields[$key]) && $fields[$key] !== '') {
                $seo_fields[$key] = $fields[$key];
                $updated[] = $key;
            }
        }
        if (!empty($seo_fields)) {
            $this->set_seo_meta($post_id, $seo_fields);
        }

        // Robots / noindex — needs special handling per SEO plugin
        if (isset($fields['robots'])) {
            $this->set_robots_meta($post_id, $fields['robots']);
            $updated[] = 'robots';
        }

        return $updated;
    }

    /**
     * Set robots/noindex meta on a post via the detected SEO plugin.
     *
     * Accepts either:
     *   - string: "noindex", "noindex,nofollow", "index,follow"
     *   - object: { noindex: true, nofollow: false }
     */
    private function set_robots_meta($post_id, $robots) {
        $settings = get_option($this->settings_option, []);
        $seo_plugin = $settings['seo_plugin'] ?? 'auto';
        if ($seo_plugin === 'auto') {
            $seo_plugin = $this->detect_seo_plugin();
        }

        // Normalize to flags
        $noindex = false;
        $nofollow = false;
        if (is_string($robots)) {
            $lower = strtolower($robots);
            $noindex = strpos($lower, 'noindex') !== false;
            $nofollow = strpos($lower, 'nofollow') !== false;
        } elseif (is_array($robots)) {
            $noindex = !empty($robots['noindex']);
            $nofollow = !empty($robots['nofollow']);
        }

        switch ($seo_plugin) {
            case 'yoast':
                // Yoast stores robots as _yoast_wpseo_meta-robots-noindex (1=noindex, 0=default)
                // and _yoast_wpseo_meta-robots-nofollow (1=nofollow, 0=default)
                update_post_meta($post_id, '_yoast_wpseo_meta-robots-noindex', $noindex ? '1' : '0');
                update_post_meta($post_id, '_yoast_wpseo_meta-robots-nofollow', $nofollow ? '1' : '0');
                break;

            case 'rankmath':
                // RankMath stores robots as a serialized array in rank_math_robots
                $rm_robots = [];
                $rm_robots[] = $noindex ? 'noindex' : 'index';
                $rm_robots[] = $nofollow ? 'nofollow' : 'follow';
                update_post_meta($post_id, 'rank_math_robots', $rm_robots);
                break;

            case 'aioseo':
                update_post_meta($post_id, '_aioseo_noindex', $noindex ? '1' : '0');
                update_post_meta($post_id, '_aioseo_nofollow', $nofollow ? '1' : '0');
                break;

            default:
                update_post_meta($post_id, '_sadie_robots_noindex', $noindex ? '1' : '0');
                update_post_meta($post_id, '_sadie_robots_nofollow', $nofollow ? '1' : '0');
                break;
        }
    }

