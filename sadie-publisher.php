class Sadie_Publisher {

    private static $instance = null;

    // Option keys
    private $api_key_option = 'sadie_publisher_api_key';
    private $project_token_option = 'sadie_publisher_project_token';
    private $settings_option = 'sadie_publisher_settings';
    private $log_option = 'sadie_publisher_audit_log';

    public static function get_instance() {
        if (null === self::$instance) {
            self::$instance = new self();
        }
        return self::$instance;
    }

    private function __construct() {
        add_action('admin_menu', [$this, 'add_admin_menu']);
        add_action('admin_init', [$this, 'register_settings']);
        add_action('rest_api_init', [$this, 'register_rest_routes']);
        // v3.1.0: serve the IndexNow key file at site root (e.g. /{key}.txt).
        // Lets us run IndexNow on hosts that strip the Authorization header
        // (so RankMath's app-password setup 401s) — keyed via the HMAC channel.
        // v3.1.1: hooked on template_redirect, NOT init. This class is
        // instantiated from inside an init callback (see bottom of file), so an
        // init hook registered here fires unreliably; template_redirect runs
        // after init and is the canonical place to short-circuit a request.
        add_action('template_redirect', [$this, 'maybe_serve_indexnow_key'], 0);
        // v3.0.16: render _sadie_schema post meta into <head> on singular pages.
        add_action('wp_head', [$this, 'render_sadie_schema'], 20);
        add_action('admin_enqueue_scripts', [$this, 'enqueue_admin_scripts']);

        register_activation_hook(__FILE__, [$this, 'activate']);
        register_deactivation_hook(__FILE__, [$this, 'deactivate']);
    }

    // =========================================================================
    // INDEXNOW (v3.1.0)
    // =========================================================================

    /**
     * Serve the IndexNow key file at the site root (e.g. /{key}.txt). Runs on
     * `init` so the key file is reachable without a rewrite-rule flush.
     */
    public function maybe_serve_indexnow_key() {
        $key = get_option('sadie_indexnow_key', '');
        if (!$key || !is_string($key)) {
            return;
        }
        $uri  = isset($_SERVER['REQUEST_URI']) ? wp_unslash($_SERVER['REQUEST_URI']) : '';
        $path = (string) parse_url($uri, PHP_URL_PATH);
        if (basename(rtrim($path, '/')) === $key . '.txt') {
            // Override WP's 404 (the query already resolved this unknown path to
            // a 404 before template_redirect); IndexNow requires a 200.
            status_header(200);
            nocache_headers();
            header('Content-Type: text/plain; charset=UTF-8');
            header('X-Robots-Tag: noindex');
            echo $key;
            exit;
        }
    }

    /** Set the IndexNow key (stored as an option, served at root). */
    public function handle_set_indexnow_key($request) {
        $params = $request->get_json_params();
        $key = isset($params['key']) ? sanitize_text_field($params['key']) : '';
        if (!preg_match('/^[A-Za-z0-9-]{8,128}$/', $key)) {
            return new WP_Error('invalid_key', 'IndexNow key must be 8-128 chars of [A-Za-z0-9-].', ['status' => 400]);
        }
        update_option('sadie_indexnow_key', $key, false);
        $this->audit_log('indexnow_key', true, $this->get_client_ip(), 'Key set');
        return [
            'success'      => true,
            'key'          => $key,
            'key_location' => home_url('/' . $key . '.txt'),
        ];
    }

    /** Read the current IndexNow key (for verification). */
    public function handle_get_indexnow_key($request) {
        $key = get_option('sadie_indexnow_key', '');
        return [
            'success'      => true,
            'key'          => $key ?: null,
            'key_location' => $key ? home_url('/' . $key . '.txt') : null,
        ];
    }

    /**
     * Notify IndexNow of a changed URL. Fire-and-forget, non-blocking; a no-op
     * until a key is set, so it is safe on every site.
     */
    private function ping_indexnow($url) {
        $key = get_option('sadie_indexnow_key', '');
        if (!$key || !$url || !is_string($url)) {
            return;
        }
        $host = parse_url(home_url(), PHP_URL_HOST);
        if (!$host) {
            return;
        }
        $body = wp_json_encode([
            'host'        => $host,
            'key'         => $key,
            'keyLocation' => home_url('/' . $key . '.txt'),
            'urlList'     => [$url],
        ]);
        wp_remote_post('https://api.indexnow.org/indexnow', [
            'timeout'  => 8,
            'blocking' => false,
            'headers'  => ['Content-Type' => 'application/json; charset=utf-8'],
            'body'     => $body,
        ]);
    }

    // =========================================================================
    // ACTIVATION / DEACTIVATION
    // =========================================================================

    public function activate() {
        if (version_compare(PHP_VERSION, SADIE_PUBLISHER_MIN_PHP, '<')) {
            deactivate_plugins(plugin_basename(__FILE__));
            wp_die(sprintf(
                'Sadie requires PHP %s or higher. You are running PHP %s.',
                SADIE_PUBLISHER_MIN_PHP,
                PHP_VERSION
            ));
        }

        if (!get_option($this->api_key_option)) {
            update_option($this->api_key_option, $this->generate_api_key());
        }
        if (!get_option($this->project_token_option)) {
            update_option($this->project_token_option, $this->generate_project_token());
        }

        // Initialize audit log
        if (!get_option($this->log_option)) {
            update_option($this->log_option, []);
        }

        // Store activation timestamp
        update_option('sadie_publisher_activated_at', current_time('mysql'));

        // v3.0.3 — default HMAC on for new installs. Previously off by
        // default which meant a leaked API key alone was a site takeover.
        // Existing sites keep their current setting.
        $settings = get_option($this->settings_option);
        if (!is_array($settings) || !isset($settings['hmac_enabled'])) {
            $settings = is_array($settings) ? $settings : [];
            $settings['hmac_enabled'] = 1;
            update_option($this->settings_option, $settings);
        }
    }

